"""Publish a release:build game package as the GitHub Release ``game/<patch>-<n>``.

The release is tagged on the ackness/repoe master commit that produced the
package. Its assets are ``pobr-game-<patch>.zip`` (the release:build zip, byte
for byte), ``receipt.json`` and ``SHA256SUMS``; the release body is generated
from the receipt. ``<n>`` starts at 1 per patch and is one above the highest
``game/<patch>-<n>`` tag on the remote.

Without ``--yes`` nothing is tagged, pushed or released: the command builds (or,
with ``--reuse``, verifies the existing build of HEAD), stages the assets under
``.cache/release/publish/`` and prints exactly what ``--yes`` would run. In a
dry run, preflight problems (dirty tree, HEAD not on origin/master) and network
failures are reported instead of stopping the staging; with ``--yes`` they
refuse. See RELEASING.md.
"""

import argparse
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import sys
import zipfile

from RePoE.data_publication import decode, pin, require
from RePoE.release import build

REPOSITORY = "ackness/repoe"
REMOTE = "origin"
BRANCH = "master"
STAGE = build.CACHE / "publish"
MARKER = ".release-publish"
TAG_PREFIX = "game/"


def log(message):
    print(f"release:publish: {message}", file=sys.stderr, flush=True)


# --- pure parts (no network, no Git) -------------------------------------------------------------


def asset_name(patch):
    return f"pobr-game-{patch}.zip"


def tag_name(patch, sequence):
    return f"{TAG_PREFIX}{patch}-{sequence}"


def sha256sums(digests):
    """GNU ``sha256sum`` lines (``<hex>  <name>``), sorted by file name."""
    return "".join(f"{digests[name]}  {name}\n" for name in sorted(digests))


def remote_tags(ls_remote):
    """``{tag: commit}`` from ``git ls-remote --tags`` output; annotated tags resolve to their peeled commit."""
    tags = {}
    for line in ls_remote.splitlines():
        if not line.strip():
            continue
        oid, ref = line.split("\t", 1)
        name = ref.removeprefix("refs/tags/")
        if name.endswith("^{}"):
            tags[name[:-3]] = oid
        else:
            tags.setdefault(name, oid)
    return tags


def sequences(tags, patch):
    """``{n: tag}`` of the ``game/<patch>-<n>`` tags among ``tags`` (other names are ignored)."""
    pattern = re.compile(re.escape(tag_name(patch, "")) + r"([1-9][0-9]*)")
    return {int(m[1]): tag for tag in tags if (m := pattern.fullmatch(tag))}


def next_sequence(tags, patch):
    """One above the highest ``game/<patch>-<n>`` tag; 1 for a patch without one."""
    return max(sequences(tags, patch), default=0) + 1


def stage(build_dir, out):
    """Stage the release assets of a release:build output directory under ``out/assets``.

    The zip and receipt are verified against the build's ``package.json`` and
    copied under their asset names; ``SHA256SUMS`` pins both. Returns what was
    staged; no network or Git access.
    """
    build_dir, out = Path(build_dir), Path(out)
    package = decode((build_dir / "package.json").read_bytes())
    receipt_raw = (build_dir / "receipt.json").read_bytes()
    receipt = decode(receipt_raw)
    require(package.get("schema") == build.PACKAGE, f"{build_dir}: not a release:build output")
    require(
        pin(receipt_raw) == {k: package["receipt"][k] for k in ("bytes", "sha256")},
        "receipt.json differs from its pin in package.json",
    )
    require(receipt.get("schema") == build.RECEIPT, f"{build_dir}/receipt.json: unexpected schema")
    require(package["target"] == receipt["target"], "package.json and receipt.json name different targets")
    require("contract" in receipt["producer"], "receipt.json does not record the PoBR contract; rebuild it")
    zip_path = build_dir / package["package"]["path"]
    zip_pin = build.file_pin(zip_path)
    require(zip_pin == {k: package["package"][k] for k in ("bytes", "sha256")}, f"{zip_path} differs from package.json")
    with zipfile.ZipFile(zip_path) as archive:
        require(archive.testzip() is None, f"{zip_path}: corrupt member")
    patch = receipt["target"]["game_patch"]
    if out.exists():
        require((out / MARKER).is_file(), f"Refusing to replace a non-publish directory: {out}")
        shutil.rmtree(out)
    assets = out / "assets"
    assets.mkdir(parents=True)
    (out / MARKER).write_text("generated by RePoE.release.publish\n")
    shutil.copyfile(zip_path, assets / asset_name(patch))
    (assets / "receipt.json").write_bytes(receipt_raw)
    pins = {asset_name(patch): zip_pin, "receipt.json": pin(receipt_raw)}
    for name, expected in pins.items():
        require(build.file_pin(assets / name) == expected, f"Staged {name} changed while copying")
    (assets / "SHA256SUMS").write_text(sha256sums({name: value["sha256"] for name, value in pins.items()}))
    pins["SHA256SUMS"] = build.file_pin(assets / "SHA256SUMS")
    return {"directory": out, "assets": dict(sorted(pins.items())), "receipt": receipt, "package": package}


def release_body(staged, tag, sequence):
    """The generated GitHub Release body: what this package is and how to pin it."""
    receipt, package = staged["receipt"], staged["package"]
    target, producer, contract = receipt["target"], receipt["producer"], receipt["producer"]["contract"]
    patch = target["game_patch"]
    zip_name = asset_name(patch)
    zip_pin = staged["assets"][zip_name]
    counts = receipt["provenance"]
    provenance = ", ".join(f"{counts[group]} {group}" for group in build.PROVENANCE if group in counts)
    classes = ", ".join(f"{kind} {count}" for kind, count in sorted(receipt["summary"].items()))
    identical = "yes" if package["package"]["identical_to_reference"] else "no"
    return (
        f"PoBR game package for {target['game']} {patch} ({target['realm']}), sequence {sequence}.\n"
        "\n"
        f"- Producer: `{producer['repository']}@{producer['commit']}` (the commit `{tag}` names)\n"
        f"- Data contract: `pobr_data::CONTRACT_VERSION` {contract['version']}, built against "
        f"`{contract['repository']}` `{contract['tag']}` (`{contract['commit']}`)\n"
        f"- `{zip_name}`: {zip_pin['bytes']} bytes, SHA-256 `{zip_pin['sha256']}`\n"
        f"- Members: {provenance}; root manifest: {package['manifest']['class']}\n"
        f"- Classes: {classes}\n"
        f"- Identical to the reference package `{receipt['reference']['package']}`: {identical}\n"
        "\n"
        f"Pin it in PoBR with `mise run data:bump {REPOSITORY} {tag}`. `receipt.json` records every input pin; "
        "`SHA256SUMS` pins the other assets.\n"
        "\n"
        "Generated by `mise run release:publish`.\n"
    )


def tag_message(staged, tag):
    patch = staged["receipt"]["target"]["game_patch"]
    sums = sha256sums({name: value["sha256"] for name, value in staged["assets"].items() if name != "SHA256SUMS"})
    return f"PoBR game package {patch} ({tag})\n\n{sums}"


def commands(staged, tag, commit, remote=REMOTE, repository=REPOSITORY):
    """The commands ``--yes`` runs, in order."""
    directory = staged["directory"]
    assets = [str(directory / "assets" / name) for name in staged["assets"]]
    return [
        ["git", "tag", "--annotate", "--file", str(directory / "tag-message.txt"), tag, commit],
        ["git", "push", remote, f"refs/tags/{tag}"],
        ["gh", "release", "create", tag, "--repo", repository, "--verify-tag", "--title", tag]
        + ["--notes-file", str(directory / "release-notes.md"), *assets],
    ]


# --- Git preflight -------------------------------------------------------------------------------


def git(repo, *args, online=False):
    """Run Git; offline calls must not lazily fetch (as in release:build)."""
    return build.git(repo, *args, check=False, online=online)


def preflight(repo, remote=REMOTE, branch=BRANCH, fetch=True):
    """Check HEAD is publishable: a clean tree on a commit of ``<remote>/<branch>``.

    Returns ``(commit, problems, warnings)``. With ``fetch``, the branch is
    fetched first; a failed fetch is a warning and the local remote-tracking
    ref is used (a real publish treats warnings as problems).
    """
    problems, warnings = [], []
    head = git(repo, "rev-parse", "--verify", "HEAD^{commit}")
    require(head.returncode == 0, f"{repo}: no HEAD commit")
    commit = head.stdout.decode().strip()
    status = git(repo, "status", "--porcelain", "--untracked-files=all").stdout.decode().splitlines()
    if status:
        problems.append(f"the working tree is not clean ({len(status)} paths, e.g. {status[0][3:]})")
    tracking = f"refs/remotes/{remote}/{branch}"
    if fetch:
        fetched = git(repo, "fetch", "--quiet", "--no-tags", remote, f"+refs/heads/{branch}:{tracking}", online=True)
        if fetched.returncode:
            warnings.append(
                f"could not fetch {remote}/{branch} ({fetched.stderr.decode().strip()}); using the local ref"
            )
    on_branch = git(repo, "merge-base", "--is-ancestor", commit, tracking).returncode
    if on_branch == 1:
        problems.append(f"HEAD {commit} is not on {remote}/{branch}")
    elif on_branch:
        problems.append(f"no {remote}/{branch} ref to check HEAD against")
    return commit, problems, warnings


def list_remote_tags(repo, remote=REMOTE):
    """``{tag: commit}`` of the remote's ``game/*`` tags, or None when the remote cannot be listed."""
    result = git(repo, "ls-remote", "--tags", remote, f"refs/tags/{TAG_PREFIX}*", online=True)
    if result.returncode:
        log(f"could not list {remote}'s tags: {result.stderr.decode().strip()}")
        return None
    return remote_tags(result.stdout.decode())


def plan_sequence(repo, patch, commit, tags):
    """``(sequence, problems)`` for HEAD given the remote tags (None: unknown)."""
    if tags is None:
        return None, [f"the remote's {TAG_PREFIX}{patch}-* tags could not be listed, so <n> is unknown"]
    published = sequences(tags, patch)
    problems = [
        f"HEAD is already published as {published[n]}" for n in sorted(published) if tags[published[n]] == commit
    ]
    sequence = next_sequence(tags, patch)
    if git(repo, "rev-parse", "--quiet", "--verify", f"refs/tags/{tag_name(patch, sequence)}").returncode == 0:
        problems.append(f"a local tag {tag_name(patch, sequence)} exists that the remote does not have; delete it")
    return sequence, problems


# --- command -------------------------------------------------------------------------------------


def built(args, config):
    """The release:build output for HEAD: rebuilt, or with ``--reuse`` the existing one if it matches HEAD."""
    config, lock, *_, config_pins = build.load_config(config)
    target = lock["target"]
    out = build.CACHE / f"{target['game']}-{target['realm']}-{target['game_patch']}"
    if args.reuse:
        receipt = decode((out / "receipt.json").read_bytes())
        current = build.producer_identity(args.repo, Path(args.adapter).absolute(), config, config_pins)
        require(receipt["producer"] == current, f"{out} was not built from this checkout; rerun without --reuse")
        log(f"reusing {build.display(out)}")
        return out
    log("running release:build")
    out, receipt, outcome = build.build(config, out, args.adapter, build.CACHE, args.fetch, repo=args.repo)
    print(build.report(receipt, outcome), file=sys.stderr)
    return out


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--config", type=Path, help="release declaration release/<patch> (default: highest patch)")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true", help="stage and print the plan only (the default)")
    mode.add_argument("--yes", action="store_true", help="tag, push and create the GitHub Release")
    parser.add_argument("--reuse", action="store_true", help="reuse the existing release:build output of HEAD")
    parser.add_argument("--fetch", action="store_true", help="release:build --fetch: fetch missing pinned commits")
    parser.add_argument(
        "--allow-different",
        action="store_true",
        help="publish a package that differs from the lock's reference package (a new patch or data change)",
    )
    parser.add_argument("--adapter", type=Path, default=build.ADAPTER, help=argparse.SUPPRESS)
    parser.add_argument("--repo", type=Path, default=build.ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    try:
        commit, problems, warnings = preflight(args.repo)
        if args.yes and (problems or warnings):
            parser.exit(
                1, "release:publish: refusing to publish:\n" + "".join(f"  - {p}\n" for p in problems + warnings)
            )
        config = args.config or build.default_config()
        out = built(args, config)
        staged = stage(out, STAGE / out.name)
        receipt, package = staged["receipt"], staged["package"]
        if receipt["producer"]["commit"] != commit or receipt["producer"]["dirty"]:
            problems.append("the package was not built from a clean HEAD")
        if not package["package"]["identical_to_reference"] and not args.allow_different:
            problems.append("the package differs from the reference package (pass --allow-different if intended)")
        patch = receipt["target"]["game_patch"]
        sequence, sequence_problems = plan_sequence(args.repo, patch, commit, list_remote_tags(args.repo))
        problems += sequence_problems
    except (ValueError, KeyError, TypeError, OSError, zipfile.BadZipFile) as error:
        parser.exit(1, f"release:publish: {error}\n")

    tag = tag_name(patch, sequence if sequence is not None else "<n>")
    directory = staged["directory"]
    (directory / "release-notes.md").write_text(release_body(staged, tag, sequence if sequence else "<n>"))
    (directory / "tag-message.txt").write_text(tag_message(staged, tag))
    steps = commands(staged, tag, commit)
    print(f"staged: {build.display(directory)}")
    for name, value in staged["assets"].items():
        print(f"  {name}  {value['bytes']} bytes  sha256 {value['sha256']}")
    print(
        "SHA256SUMS:\n" + "".join(f"  {line}\n" for line in (directory / "assets/SHA256SUMS").read_text().splitlines())
    )
    print(f"tag: {tag} -> {commit}")
    print(f"release body: {build.display(directory / 'release-notes.md')}")
    print("commands:\n" + "".join(f"  {shlex.join(step)}\n" for step in steps))
    for warning in warnings:
        print(f"warning: {warning}")
    if problems:
        print("publish refused:\n" + "".join(f"  - {p}\n" for p in problems))
        raise SystemExit(1)
    if not args.yes:
        print("dry run: nothing was tagged, pushed or released; rerun with --yes to publish")
        return
    for index, step in enumerate(steps):
        log(shlex.join(step))
        if subprocess.run(step, cwd=args.repo, check=False).returncode:
            remaining = "".join(f"  {shlex.join(s)}\n" for s in steps[index + 1 :])
            parser.exit(1, f"release:publish: step failed: {shlex.join(step)}\nremaining:\n{remaining}")
    print(f"published https://github.com/{REPOSITORY}/releases/tag/{tag}")


if __name__ == "__main__":
    main()
